VIEWS: set[str] = set()


def tables_for(phase: str) -> list[str]:
    key = phase.zfill(2)
    if key not in PHASES:
        raise SystemExit(f"phase {key!r} is not in scripts/phase_manifest.py")
    return PHASES[key]


def all_tables() -> set[str]:
    return {t for tables in PHASES.values() for t in tables}
