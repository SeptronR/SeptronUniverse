"""Shared renderers — Prompts/36 §36.6 ``render_service`` (used by Phase 36 runs / registers / statutory files and by
the Phase 32 cycle / submission exports).

* ``render_xlsx(sheets, header)`` — openpyxl **write-only** workbook: a title block (institution, report, scope,
  generated by / on), bold filled header row, freeze panes under it, number formats per column type (``money`` columns
  are paise → ₹ ``#,##0.00``; ``pct`` → ``0.00"%"``; dates ISO), totals row for ``total`` columns.
* ``render_csv(columns, rows)`` — UTF-8 with BOM (Excel opens Indic text correctly), money in rupees.
* ``render_pdf(...)`` — the Phase 26 PDF path (``app.utils.pdf.render_pdf``: WeasyPrint, else the built-in writer) with
  the report layout (``portrait`` / ``landscape`` / ``ledger``): letterhead block from ``institution_profile``, page
  numbers, generated-by / on (date only, so identical data gives an identical checksum), ``DRAFT`` watermark when
  ``params.draft``; the ledger layout prints page-wise totals (``rows_per_page``) and a grand total.
* ``render_docx(title, blocks)`` — WordprocessingML written directly (no python-docx dependency; same writer the
  Phase 32 SSR / AQAR / SAR exports used, moved here).
* ``render_json(columns, rows)``.
"""

