CONTENT_TYPES: dict[str, str] = {
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "csv": "text/csv",
    "pdf": "application/pdf",
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "json": "application/json",
    "zip": "application/zip",
}

LEDGER_ROWS_PER_PAGE = 30


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _col(c: Any) -> dict[str, Any]:
    return c.as_dict() if hasattr(c, "as_dict") else dict(c)


def _cell(value: Any, ctype: str) -> Any:
    """Value as written to a file (paise → rupees, JSON → text, UUID → str)."""
    if value is None:
        return None
    if ctype == "money" and isinstance(value, int | float | Decimal):
        return round(float(value) / 100, 2)
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, dict | list):
        return json.dumps(value, default=str, ensure_ascii=False)
    if isinstance(value, datetime):
        return value.replace(tzinfo=None) if ctype in ("datetime",) else value.isoformat(sep=" ", timespec="minutes")
    if isinstance(value, date | bool | int | float | str):
        return value
    return str(value)


def _text(value: Any, ctype: str) -> str:
    v = _cell(value, ctype)
    if v is None:
        return ""
    if ctype == "money":
        return f"{v:,.2f}"
    if ctype == "pct":
        return f"{float(v):.2f}%"
    if isinstance(v, datetime):
        return v.strftime("%Y-%m-%d %H:%M")
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, bool):
        return "Yes" if v else "No"
    return str(v)


# ---- xlsx -----------------------------------------------------------------------------------------------------------------
def render_xlsx(sheets: list[dict[str, Any]], header: dict[str, Any] | None = None) -> bytes:
    """``sheets``: ``[{title, columns: [ReportColumn | dict], rows: [dict], totals: {key: value}}]``."""
    from openpyxl import Workbook
    from openpyxl.cell import WriteOnlyCell
    from openpyxl.styles import Alignment, Font, PatternFill

    header = header or {}
    wb = Workbook(write_only=True)
    bold = Font(bold=True)
    head_font = Font(bold=True, color="FFFFFF")
    fill = PatternFill("solid", fgColor="1F4E79")
    formats = {"money": "#,##0.00", "pct": '0.00"%"', "int": "#,##0", "number": "#,##0.00", "date": "yyyy-mm-dd"}
    for sheet in sheets or [{"title": "Report", "columns": [], "rows": []}]:
        title = re.sub(r"[\[\]:*?/\\]", "-", str(sheet.get("title") or "Report"))[:31].strip("'") or "Report"
        while title in wb.sheetnames:
            title = f"{title[:28]}~{len(wb.sheetnames)}"
        ws = wb.create_sheet(title)
        cols = [_col(c) for c in sheet.get("columns") or []] or [{"key": "-", "label": "(no columns)", "type": "str"}]
        banner = [
            header.get("institution"),
            sheet.get("title") or header.get("title"),
            header.get("scope"),
            " · ".join(x for x in (header.get("generated_by"), header.get("generated_on")) if x),
        ]
        top = 0
        for line in banner:
            if line:
                c = WriteOnlyCell(ws, value=str(line))
                c.font = bold
                ws.append([c])
                top += 1
        if header.get("draft"):
            c = WriteOnlyCell(ws, value="DRAFT")
            c.font = Font(bold=True, color="C00000")
            ws.append([c])
            top += 1
        head_row = []
        for col in cols:
            c = WriteOnlyCell(ws, value=col.get("label") or col["key"])
            c.font, c.fill, c.alignment = head_font, fill, Alignment(wrap_text=True, vertical="center")
            head_row.append(c)
        ws.append(head_row)
        ws.freeze_panes = f"A{top + 2}"
        for r in sheet.get("rows") or []:
            out = []
            for col in cols:
                c = WriteOnlyCell(ws, value=_cell(r.get(col["key"]), col.get("type", "str")))
                fmt = formats.get(col.get("type", "str"))
                if fmt:
                    c.number_format = fmt
                out.append(c)
            ws.append(out)
        totals = sheet.get("totals") or {}
        if totals:
            out = []
            for i, col in enumerate(cols):
                v = totals.get(col["key"])
                c = WriteOnlyCell(ws, value="Total" if i == 0 and v is None else _cell(v, col.get("type", "str")))
                c.font = bold
                fmt = formats.get(col.get("type", "str"))
                if fmt and v is not None:
                    c.number_format = fmt
                out.append(c)
            ws.append(out)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def xlsx_sheets(sheets: dict[str, list[dict[str, Any]]]) -> bytes:
    """Plain dict-rows workbook (one sheet per key) — the Phase 32 export shape."""
    out = []
    for name, rows in (sheets or {"(empty)": []}).items():
        keys = list(rows[0].keys()) if rows else ["(no rows)"]
        out.append({"title": name[:30], "columns": [{"key": k, "label": k, "type": "str"} for k in keys], "rows": rows})
    return render_xlsx(out)


# ---- csv ------------------------------------------------------------------------------------------------------------------
def render_csv(columns: list[Any], rows: list[dict[str, Any]]) -> bytes:
    cols = [_col(c) for c in columns]
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([c.get("label") or c["key"] for c in cols])
    for r in rows:
        w.writerow([_text(r.get(c["key"]), c.get("type", "str")) for c in cols])
    return ("﻿" + buf.getvalue()).encode("utf-8")


# ---- json -----------------------------------------------------------------------------------------------------------------
def render_json(columns: list[Any], rows: list[dict[str, Any]], meta: dict[str, Any] | None = None) -> bytes:
    cols = [_col(c) for c in columns]
    body = {
        "meta": meta or {},
        "columns": cols,
        "rows": [{c["key"]: _cell(r.get(c["key"]), c.get("type", "str")) for c in cols} for r in rows],
    }
    return json.dumps(body, default=str, ensure_ascii=False, sort_keys=True).encode("utf-8")


# ---- pdf ------------------------------------------------------------------------------------------------------------------
_PDF_CSS = {
    "portrait": "@page { size: A4; margin: 14mm 12mm 16mm; }",
    "landscape": "@page { size: A4 landscape; margin: 12mm; }",
    "ledger": "@page { size: A4 landscape; margin: 10mm; }",
}


def render_pdf(
    title: str,
    columns: list[Any],
    rows: list[dict[str, Any]],
    *,
    layout: str = "portrait",
    header: dict[str, Any] | None = None,
    sections: list[dict[str, Any]] | None = None,
    summary: list[tuple[str, Any]] | None = None,
    signoff: list[dict[str, Any]] | None = None,
) -> bytes:
    """Letterhead + table(s); ``ledger`` adds page-wise totals. Deterministic for identical input (no timestamps)."""
    from app.utils.pdf import render_pdf as _pdf

    header = header or {}
    draft = bool(header.get("draft"))
    blocks: list[dict[str, Any]] = [{"title": None, "columns": columns, "rows": rows}] if columns else []
    blocks += list(sections or [])
    css = (
        _PDF_CSS.get(layout, _PDF_CSS["portrait"])
        + " @page { @bottom-right { content: 'Page ' counter(page) ' of ' counter(pages); font-size: 8pt; } }"
        " body { font-family: sans-serif; font-size: 8.5pt; } h1 { font-size: 13pt; margin: 0; }"
        " .lh { border-bottom: 2px solid #1F4E79; margin-bottom: 6px; padding-bottom: 4px; }"
        " .meta { color: #555; font-size: 7.5pt; } table { border-collapse: collapse; width: 100%; margin: 6px 0; }"
        " th { background: #1F4E79; color: #fff; text-align: left; } th, td { border: 1px solid #999; padding: 2px 4px; }"
        " td.n { text-align: right; } tr.tot td { font-weight: bold; background: #eef; }"
        " .wm { position: fixed; top: 40%; left: 20%; font-size: 90pt; color: rgba(200,0,0,0.12); transform: rotate(-30deg); }"
        " .pb { page-break-after: always; }"
    )
    html: list[str] = [f"<html><head><meta charset='utf-8'><style>{css}</style></head><body>"]
    lines: list[str] = []
    if draft:
        html.append("<div class='wm'>DRAFT</div>")
        lines.append("*** DRAFT ***")
    lh = [x for x in (header.get("institution"), header.get("address")) if x]
    html.append(
        "<div class='lh'>"
        + (f"<img src='{h(header['logo'])}' style='height:36px;float:right'/>" if header.get("logo") else "")
        + "".join(f"<div><b>{h(str(x))}</b></div>" for x in lh)
        + f"<h1>{h(title)}</h1><div class='meta'>"
        + h(
            " · ".join(
                str(x) for x in (header.get("scope"), header.get("generated_by"), header.get("generated_on")) if x
            )
        )
        + "</div></div>"
    )
    lines += [
        *map(str, lh),
        title,
        " · ".join(str(x) for x in (header.get("scope"), header.get("generated_by"), header.get("generated_on")) if x),
    ]
    if summary:
        html.append(
            "<table>" + "".join(f"<tr><th>{h(str(k))}</th><td>{h(str(v))}</td></tr>" for k, v in summary) + "</table>"
        )
        lines += [f"{k}: {v}" for k, v in summary]
    for block in blocks:
        cols = [_col(c) for c in block.get("columns") or []]
        brows = list(block.get("rows") or [])
        if block.get("title"):
            html.append(f"<h3>{h(str(block['title']))}</h3>")
            lines += ["", str(block["title"])]
        if not cols:
            continue
        lines.append(" | ".join(c.get("label") or c["key"] for c in cols))
        per_page = LEDGER_ROWS_PER_PAGE if layout == "ledger" else max(len(brows), 1)
        chunks = [brows[i : i + per_page] for i in range(0, len(brows), per_page)] or [[]]
        grand: dict[str, float] = {}
        for n, chunk in enumerate(chunks):
            html.append("<table><tr>" + "".join(f"<th>{h(c.get('label') or c['key'])}</th>" for c in cols) + "</tr>")
            page: dict[str, float] = {}
            for r in chunk:
                tds = []
                for c in cols:
                    v = r.get(c["key"])
                    t = c.get("type", "str")
                    num = t in ("money", "int", "number", "pct")
                    tds.append(f"<td class='{'n' if num else ''}'>{h(_text(v, t))}</td>")
                    if c.get("total") and isinstance(v, int | float | Decimal):
                        page[c["key"]] = page.get(c["key"], 0) + float(v)
                html.append("<tr>" + "".join(tds) + "</tr>")
                lines.append(" | ".join(_text(r.get(c["key"]), c.get("type", "str")) for c in cols))
            for k, v in page.items():
                grand[k] = grand.get(k, 0) + v
            if layout == "ledger" and page:
                html.append(_total_row(cols, page, "Page total"))
                lines.append(
                    "Page total: "
                    + ", ".join(
                        f"{k}={_text(v, 'money' if k.endswith('_paise') else 'number')}" for k, v in page.items()
                    )
                )
            html.append("</table>")
            if layout == "ledger" and n < len(chunks) - 1:
                html.append("<div class='pb'></div>")
        if grand:
            html.append("<table>" + _total_row(cols, grand, "Grand total") + "</table>")
            lines.append(
                "Grand total: "
                + ", ".join(f"{k}={_text(v, 'money' if k.endswith('_paise') else 'number')}" for k, v in grand.items())
            )
    if signoff is not None:
        html.append("<table><tr><th>Role</th><th>Signed by</th><th>On</th></tr>")
        for s in signoff or [{"role": "—", "user_name": "", "at": ""}]:
            html.append(
                f"<tr><td>{h(str(s.get('role') or ''))}</td><td>{h(str(s.get('user_name') or ''))}</td><td>{h(str(s.get('at') or ''))}</td></tr>"
            )
            lines.append(f"Sign-off {s.get('role')}: {s.get('user_name') or ''} {s.get('at') or ''}")
        html.append("</table>")
    html.append("</body></html>")
    return _pdf("".join(html), lines, title=title)


def _total_row(cols: list[dict[str, Any]], sums: dict[str, float], label: str) -> str:
    cells = []
    for i, c in enumerate(cols):
        if c["key"] in sums:
            cells.append(f"<td class='n'>{h(_text(sums[c['key']], c.get('type', 'number')))}</td>")
        else:
            cells.append(f"<td>{h(label) if i == 0 else ''}</td>")
    return "<tr class='tot'>" + "".join(cells) + "</tr>"


# ---- docx -----------------------------------------------------------------------------------------------------------------
def docx_bytes(title: str, blocks: list[tuple[str, Any]]) -> bytes:
    """Minimal .docx: ``("h1"|"h2"|"p", text)`` and ``("table", [[cell, …], …])`` blocks."""

    def para(text: str, style: str | None = None) -> str:
        ppr = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ""
        runs = "".join(
            f'<w:r><w:t xml:space="preserve">{escape(line)}</w:t></w:r>'
            + ("<w:r><w:br/></w:r>" if i < len(lines) - 1 else "")
            for lines in [str(text).splitlines() or [""]]
            for i, line in enumerate(lines)
        )
        return f"<w:p>{ppr}{runs}</w:p>"

    body: list[str] = [para(title, "Title")]
    for kind, content in blocks:
        if kind == "table":
            rows = "".join(
                "<w:tr>"
                + "".join(f'<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/></w:tcPr>{para(c)}</w:tc>' for c in row)
                + "</w:tr>"
                for row in content
            )
            body.append(
                '<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="0" w:type="auto"/>'
                '<w:tblBorders><w:top w:val="single" w:sz="4"/><w:left w:val="single" w:sz="4"/><w:bottom w:val="single" w:sz="4"/>'
                '<w:right w:val="single" w:sz="4"/><w:insideH w:val="single" w:sz="4"/><w:insideV w:val="single" w:sz="4"/></w:tblBorders>'
                f"</w:tblPr>{rows}</w:tbl>"
            )
        else:
            body.append(para(str(content), {"h1": "Heading1", "h2": "Heading2"}.get(kind)))
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>'
        + "".join(body)
        + "</w:body></w:document>"
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(
            "[Content_Types].xml",
            '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
            "</Types>",
        )
        z.writestr(
            "_rels/.rels",
            '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>'
            "</Relationships>",
        )
        z.writestr("word/document.xml", document)
    return buf.getvalue()


def render_docx(title: str, sections: list[dict[str, Any]], intro: list[str] | None = None) -> bytes:
    """Narrative statutory format: one heading + table per section (``{title, columns, rows, narrative?}``)."""
    blocks: list[tuple[str, Any]] = [("p", p) for p in intro or []]
    for s in sections:
        blocks.append(("h1", str(s.get("title") or "")))
        if s.get("narrative"):
            blocks.append(("p", str(s["narrative"])))
        cols = [_col(c) for c in s.get("columns") or []]
        if cols:
            table = [[c.get("label") or c["key"] for c in cols]]
            table += [[_text(r.get(c["key"]), c.get("type", "str")) for c in cols] for r in s.get("rows") or []]
            blocks.append(("table", table))
    return docx_bytes(title, blocks)


def zip_bytes(files: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in sorted(files.items()):
            z.writestr(name, data)
    return buf.getvalue()
