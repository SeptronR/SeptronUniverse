"""Bulk generation — Prompts/26 §26.6 ``bulk_service`` ({documents.bulk_generation}).

``POST /documents/bulk`` queues ``documents.bulk_generate`` on the ``documents`` queue for a scope (batch / section /
enrolment ids → students; staff ids → staff). The job renders one document per target through ``render()`` (so a
second run is idempotent: existing live documents are reused, earlier failures retried), records failures with a
reason (ID cards without a photo, course-completion for a student who has not completed / graduated), orders the
output by roll number / serial / name and, when asked, writes a ZIP of the PDFs (``documents.zip``) whose download is a
signed storage URL. The report lives in ``background_jobs.result``. Hall tickets and grade cards stay with their
Phase 14 / 15 jobs (which now call the same renderer).
"""

import io
import uuid
import zipfile
from typing import Any

from sqlalchemy import select

from app.core.errors import APIError, ErrorCode
from app.enums.documents import STAFF_TYPES, TEMPLATE_TYPES
from app.models.documents import IssuedDocument
from app.models.hr import Staff
from app.models.platform import BackgroundJob
from app.models.students import Student, StudentProgramEnrollment, StudentTermRecord
from app.schemas.documents import DocBulkGenerateRequest, DocBulkJobOut
from app.services.documents.common import DocumentsBase, forbidden, not_found
from app.services.documents.render_service import RenderService

DELEGATED = {"hall_ticket": "Phase 14 hall-ticket job", "grade_card": "Phase 15 grade-card job"}


class BulkService(DocumentsBase):
    async def queue(self, body: DocBulkGenerateRequest) -> DocBulkJobOut:
        from app.core.jobs import enqueue

        await self.require_feature("documents.bulk_generation")
        if not self.office():
            raise forbidden("certificates:issue required")
        self.require_writer()
        if body.template_type not in TEMPLATE_TYPES:
            raise APIError(422, ErrorCode.VALIDATION, f"Unknown template type {body.template_type}")
        if body.template_type in DELEGATED:
            raise APIError(
                422, ErrorCode.VALIDATION, f"{body.template_type} is generated by the {DELEGATED[body.template_type]}"
            )
        self.require_type(body.template_type)
        if body.template_type in STAFF_TYPES and not body.scope.staff_ids:
            raise APIError(422, ErrorCode.VALIDATION, "Staff letters need scope.staff_ids")
        job = await enqueue(
            self.db,
            self.principal,
            "documents.bulk_generate",
            body.model_dump(mode="json", by_alias=True),
            queue="documents",
        )
        return DocBulkJobOut(job_id=job.id, status=job.status)

    async def targets(self, body: DocBulkGenerateRequest) -> list[tuple[str, uuid.UUID, str, str]]:
        """``(entity_type, entity_id, sort_key, label)`` in print order."""
        sc = body.scope
        if sc.staff_ids:
            staff = (await self.db.execute(select(Staff).where(Staff.id.in_(sc.staff_ids)))).scalars().all()
            out = [("staff", s.id, s.employee_id, f"{s.first_name} {s.last_name or ''}".strip()) for s in staff]
            return sorted(out, key=lambda t: t[3] if body.print_order == "name" else t[2])
        stmt = (
            select(StudentProgramEnrollment, Student)
            .join(Student, Student.id == StudentProgramEnrollment.student_id)
            .where(StudentProgramEnrollment.institution_id == self.inst, StudentProgramEnrollment.deleted_at.is_(None))
        )
        if sc.enrollment_ids:
            stmt = stmt.where(StudentProgramEnrollment.id.in_(sc.enrollment_ids))
        if sc.batch_id:
            stmt = stmt.where(StudentProgramEnrollment.batch_id == sc.batch_id)
        if sc.section_id:
            stmt = stmt.where(
                StudentProgramEnrollment.id.in_(
                    select(StudentTermRecord.student_program_enrollment_id).where(
                        StudentTermRecord.section_id == sc.section_id
                    )
                )
            )
        rows = (await self.db.execute(stmt)).all()
        rolls: dict[uuid.UUID, str] = {}
        if rows:
            for eid, roll in (
                await self.db.execute(
                    select(StudentTermRecord.student_program_enrollment_id, StudentTermRecord.roll_number)
                    .where(StudentTermRecord.student_program_enrollment_id.in_([e.id for e, _ in rows]))
                    .order_by(StudentTermRecord.term_number)
                )
            ).all():
                if roll:
                    rolls[eid] = roll
        out = [
            ("student_program_enrollment", e.id, rolls.get(e.id) or s.registration_number, s.full_name) for e, s in rows
        ]
        return sorted(out, key=lambda t: t[3] if body.print_order == "name" else t[2])

    async def run(self, body: DocBulkGenerateRequest, job_id: uuid.UUID, progress: Any = None) -> dict[str, Any]:
        r = RenderService(self.db, self.principal, self.request, self.inst)
        targets = await self.targets(body)
        ok: list[dict[str, Any]] = []
        failed: list[dict[str, Any]] = []
        for n, (etype, eid, sort_key, label) in enumerate(targets, 1):
            reason = await self.precheck(body.template_type, etype, eid)
            if reason:
                failed.append({"entity_id": str(eid), "label": label, "reason": reason})
                continue
            try:
                async with self.db.begin_nested():
                    res = await r.render(
                        body.template_type,
                        etype,
                        eid,
                        template_id=body.template_id,
                        register=body.register_,
                        variables_override=body.variables_override,
                        job_id=job_id,
                    )
                ok.append(
                    {
                        "entity_id": str(eid),
                        "label": label,
                        "sort": sort_key,
                        "document_id": str(res.issued_document_id),
                        "document_number": res.document_number,
                        "serial_no": res.serial_no,
                        "reused": res.reused,
                    }
                )
            except APIError as exc:
                failed.append({"entity_id": str(eid), "label": label, "reason": exc.message})
            if progress is not None and n % 20 == 0:
                await progress(int(n * 90 / max(len(targets), 1)), f"{n}/{len(targets)}")
        if body.print_order == "serial":
            ok.sort(key=lambda x: (x.get("serial_no") or "", x["sort"]))
        report: dict[str, Any] = {"total": len(targets), "ok": len(ok), "failed": failed, "documents": ok}
        if body.zip and ok:
            report["zip_key"] = await self.zip(job_id, [uuid.UUID(x["document_id"]) for x in ok])
        return report

    async def precheck(self, template_type: str, etype: str, eid: uuid.UUID) -> str | None:
        if etype != "student_program_enrollment":
            return None
        e = (
            await self.db.execute(select(StudentProgramEnrollment).where(StudentProgramEnrollment.id == eid))
        ).scalar_one_or_none()
        if e is None:
            return "enrolment not found"
        if template_type == "id_card":
            photo = (await self.db.execute(select(Student.photo_url).where(Student.id == e.student_id))).scalar_one()
            if not photo:
                return "missing photo"
        if template_type == "course_completion" and e.status not in ("completed", "graduated"):
            return f"not graduated (status {e.status})"
        return None

    async def zip(self, job_id: uuid.UUID, doc_ids: list[uuid.UUID]) -> str:
        from app.core.files import build_key, get_storage

        storage = get_storage()
        docs = {
            d.id: d
            for d in (await self.db.execute(select(IssuedDocument).where(IssuedDocument.id.in_(doc_ids)))).scalars()
        }
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            for i, did in enumerate(doc_ids, 1):
                d = docs.get(did)
                if d is None:
                    continue
                try:
                    data = await storage.get(d.pdf_url)
                except Exception:  # noqa: BLE001 - a missing file is reported by its absence in the ZIP
                    continue
                zf.writestr(f"{i:04d}_{d.document_number.replace('/', '-')}.pdf", data)
        key = build_key(self.inst, "documents/bulk", f"{job_id}.zip")
        await storage.put(key, buf.getvalue(), "application/zip")
        return key

    async def status(self, job_id: uuid.UUID) -> DocBulkJobOut:
        if not self.office():
            raise forbidden("certificates:issue required")
        j = (
            await self.db.execute(
                select(BackgroundJob).where(
                    BackgroundJob.id == job_id,
                    BackgroundJob.institution_id == self.inst,
                    BackgroundJob.job_type == "documents.bulk_generate",
                )
            )
        ).scalar_one_or_none()
        if j is None:
            raise not_found("Job")
        res = dict(j.result or {})
        res.pop("zip_key", None)
        return DocBulkJobOut(
            job_id=j.id,
            status=j.status,
            progress=j.progress_pct,
            message=j.message,
            result=res or None,
            zip_url=f"/api/v1/documents/bulk/{j.id}/zip" if (j.result or {}).get("zip_key") else None,
        )

    async def zip_url(self, job_id: uuid.UUID) -> str:
        from app.core.files import get_storage

        await self.status(job_id)
        j = (await self.db.execute(select(BackgroundJob).where(BackgroundJob.id == job_id))).scalar_one()
        key = (j.result or {}).get("zip_key")
        if not key:
            raise not_found("ZIP")
        return get_storage().signed_url(key, 15 * 60)
