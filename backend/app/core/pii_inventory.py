"""PII inventory and masking audit — Prompts/43 §43.6 privacy 3.

The inventory (``app/core/pii_inventory.json``, regenerated by ``scripts/gen_pii_inventory.py`` from
``Database_Schema.sql``) classifies every personal-data column: ``identifier | contact | financial | health |
biometric | location | academic_sensitive | minor`` with a masking rule, retention class and legal basis. The masking
audit walks every response schema under ``app/schemas`` and reports fields carrying an *identifier* or *financial*
class name that are not declared through a ``Masked*`` type (``app/core/authz/masking.py``) — those must only ever
leave the API masked unless the caller holds ``<module>:view_pii``. Reviewed exceptions (e.g. a self-service view
returning the caller's own phone) live in ``scripts/pii_mask_exempt.txt`` (``Schema.field`` per line).
"""

from __future__ import annotations

import importlib
import json
import pkgutil
import re
from pathlib import Path
from typing import Any

INVENTORY_FILE = Path(__file__).with_name("pii_inventory.json")
EXEMPT_FILE = Path(__file__).resolve().parents[2] / "scripts" / "pii_mask_exempt.txt"

# column-name rules → (class, masking, retention class, legal basis); first match wins
RULES: tuple[tuple[str, str, str, str, str], ...] = (
    (
        r"^(aadhaar|aadhaar_encrypted|aadhaar_number|pan|pan_number|passport_number|voter_id|apaar_id|abc_id|uan|pf_number|esi_number|driving_licence)$",
        "identifier",
        "generic",
        "statutory_10y",
        "legal_obligation",
    ),
    (
        r"(^|_)(bank_details|bank_account|ifsc|salary|gross|net_pay|ctc|account_number|upi_id)($|_)",
        "financial",
        "secret",
        "financial_8y",
        "contract",
    ),
    (
        r"(^|_)(phone|mobile|whatsapp|email|alt_email|address|permanent_address|current_address|pincode)($|_)",
        "contact",
        "phone_email",
        "active_plus_3y",
        "contract",
    ),
    (
        r"(^|_)(blood_group|allergies|medical|diagnosis|prescription|disability|health|counselling_notes|notes_encrypted)($|_)",
        "health",
        "secret",
        "health_5y",
        "consent",
    ),
    (
        r"(^|_)(face|fingerprint|biometric|template_hash|photo_embedding)($|_)",
        "biometric",
        "secret",
        "consent_bound",
        "consent",
    ),
    (r"(^|_)(lat|lng|latitude|longitude|location|geo)($|_)", "location", "none", "operational_90d", "consent"),
    (
        r"(^|_)(caste|category|religion|minority_type|income|annual_income|is_minority)($|_)",
        "academic_sensitive",
        "generic",
        "statutory_10y",
        "legal_obligation",
    ),
    (r"^(dob|date_of_birth|guardian_name|father_name|mother_name)$", "minor", "generic", "statutory_10y", "contract"),
)
MUST_MASK = ("identifier", "financial")
SCHEMA_SUFFIXES = ("Out", "Response", "Detail", "Row", "Item", "View")


def classify(column: str) -> tuple[str, str, str, str] | None:
    for pattern, cls, masking, retention, basis in RULES:
        if re.search(pattern, column):
            return cls, masking, retention, basis
    return None


def build_from_schema(sql: str) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", sql, re.S):
        table, body = m.group(1), m.group(2)
        for col in re.findall(
            r"(?:^|,)\s*([a-z_][a-z0-9_]*)\s+(?:UUID|VARCHAR|TEXT|BYTEA|DATE|NUMERIC|INTEGER|BIGINT|SMALLINT|BOOLEAN|JSONB|INET|TIMESTAMPTZ|DOUBLE|REAL|CHAR)",
            body,
            re.M,
        ):
            c = classify(col)
            if c:
                out.append(
                    {
                        "table": table,
                        "column": col,
                        "cls": c[0],
                        "masking": c[1],
                        "retention_class": c[2],
                        "legal_basis": c[3],
                    }
                )
    return out


def load_inventory() -> list[dict[str, Any]]:
    if INVENTORY_FILE.exists():
        return list(json.loads(INVENTORY_FILE.read_text(encoding="utf-8")))
    return []


def _exempt() -> set[str]:
    if not EXEMPT_FILE.exists():
        return set()
    return {
        ln.strip()
        for ln in EXEMPT_FILE.read_text(encoding="utf-8").splitlines()
        if ln.strip() and not ln.startswith("#")
    }


def masking_audit() -> dict[str, Any]:
    from pydantic import BaseModel

    import app.schemas as schemas_pkg
    from app.core.authz.masking import pii_fields

    exempt = _exempt()
    issues: list[dict[str, Any]] = []
    checked = 0
    for mod in pkgutil.iter_modules(schemas_pkg.__path__):
        module = importlib.import_module(f"app.schemas.{mod.name}")
        for name, obj in vars(module).items():
            if not (isinstance(obj, type) and issubclass(obj, BaseModel) and obj.__module__ == module.__name__):
                continue
            if not name.endswith(SCHEMA_SUFFIXES):
                continue
            masked = pii_fields(obj)
            for field in obj.model_fields:
                c = classify(field)
                if not c or c[0] not in MUST_MASK:
                    continue
                checked += 1
                if field in masked or f"{name}.{field}" in exempt:
                    continue
                issues.append(
                    {
                        "schema_field": f"{module.__name__}.{name}.{field}",
                        "cls": c[0],
                        "masked": False,
                        "allowed_unmask_permission": "<module>:view_pii",
                    }
                )
    return {"ok": not issues, "checked": checked, "issues": issues}
