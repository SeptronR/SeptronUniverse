"""Settings (pydantic-settings) — Prompts/00_PREREQUISITE_Project_Setup.md §3.4."""

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    APP_NAME: str = "SeptronUniverse"
    APP_ENV: str = "development"
    SECRET_KEY: str
    JWT_KID: str = "k1"
    JWT_PREVIOUS_KEYS: dict[str, str] = {}
    # Phase 43: RS256 when a private key (PEM) is configured; previous public keys stay valid for the grace window
    JWT_RSA_PRIVATE_KEY: str | None = None
    JWT_RSA_PREVIOUS_PUBLIC_KEYS: dict[str, str] = {}
    # Phase 43 hardening: CSP report-only until switched; breached-password check (HIBP k-anonymity)
    CSP_ENFORCE: bool = False
    BREACHED_PASSWORD_CHECK: bool = True
    MAX_JSON_DEPTH: int = 64
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 15
    REFRESH_TOKEN_EXPIRE_DAYS: int = 7
    ALLOWED_ORIGINS: list[str] = ["http://localhost:5173"]
    PLATFORM_HOSTS: list[str] = ["localhost"]
    READ_ONLY_MODE: bool = False

    DATABASE_URL: str
    PLATFORM_DATABASE_URL: str | None = None
    DB_POOL_SIZE: int = 10
    DB_MAX_OVERFLOW: int = 20

    REDIS_URL: str
    CELERY_BROKER_URL: str
    CELERY_RESULT_BACKEND: str

    STORAGE_BACKEND: str = "local"
    UPLOAD_DIR: str = "./uploads"
    S3_BUCKET: str | None = None
    S3_REGION: str | None = None
    S3_ENDPOINT_URL: str | None = None
    AWS_ACCESS_KEY_ID: str | None = None
    AWS_SECRET_ACCESS_KEY: str | None = None
    SIGNED_URL_TTL_SECONDS: int = 900
    MAX_UPLOAD_MB: int = 25
    # builtin = signature sniffer (no native library); magic = python-magic/libmagic (Docker image, Linux)
    FILE_MIME_SNIFFER: str = "builtin"
    CLAMAV_HOST: str | None = None
    CLAMAV_PORT: int = 3310
    JOB_RETENTION_DAYS: int = 7

    SMS_PROVIDER: str = "mock"
    WHATSAPP_PROVIDER: str = "mock"
    EMAIL_PROVIDER: str = "mock"
    PUSH_PROVIDER: str = "mock"
    # Phase 39 web push (VAPID): generated by scripts/gen_vapid.py, never committed; platform_settings["push.vapid"]
    VAPID_PUBLIC_KEY: str = ""
    VAPID_PRIVATE_KEY: str = ""
    VAPID_SUBJECT: str = "mailto:support@septron.in"
    BUILD_HASH: str = "dev"
    # Phase 40 edge integration (Traefik provider + ACME callback; Phase 44 wires the edge)
    EDGE_TOKEN: str = ""
    # Phase 43/44: CI / ops callers (scan summaries, backup status) authenticate with X-Ops-Token
    INTERNAL_OPS_TOKEN: str = ""
    # Phase 44: Prometheus scrape bearer for /metrics (required in production)
    METRICS_TOKEN: str = ""
    EDGE_HOSTNAME: str = "edge.septron.in"
    PAYMENT_PROVIDER: str = "mock"
    INTEGRATION_ENCRYPTION_KEY: str
    CAPTCHA_PROVIDER: str = "none"
    CAPTCHA_SECRET: str | None = None
    CAPTCHA_SITE_KEY: str | None = None

    SENTRY_DSN: str | None = None
    LOG_LEVEL: str = "INFO"
    INSTALL_SECRET_KEY: str
    SUPERADMIN_EMAIL: str = "superadmin@universe.local"

    # ---- Phase 02: authentication policy (Prompts/02 §02.6) ----
    LOGIN_LOCKOUT_ATTEMPTS: int = 5  # failures per identifier inside LOGIN_LOCKOUT_MINUTES -> 429 RATE_LIMITED
    LOGIN_LOCKOUT_MINUTES: int = 15
    OTP_TTL_SECONDS: int = 300
    OTP_RESEND_SECONDS: int = 60
    PASSWORD_MIN_LENGTH: int = 10
    PASSWORD_HISTORY: int = 5
    PASSWORD_RESET_TTL_MINUTES: int = 60
    MFA_SETUP_TOKEN_MINUTES: int = 10
    # web origin used in password-reset / SSO redirect links (first ALLOWED_ORIGINS entry when unset)
    FRONTEND_URL: str | None = None
    SSO_PROVIDER: str = "mock"
    # development aid: run enqueued jobs inside the API process (set by scripts/dev_api_fakeredis.py; never in prod)
    JOBS_INLINE: bool = False

    @property
    def cookie_secure(self) -> bool:
        return self.APP_ENV == "production"

    @property
    def is_production(self) -> bool:
        return self.APP_ENV == "production"

    @property
    def frontend_url(self) -> str:
        return (
            self.FRONTEND_URL or (self.ALLOWED_ORIGINS[0] if self.ALLOWED_ORIGINS else "http://localhost:5173")
        ).rstrip("/")

    @field_validator("DATABASE_URL", "PLATFORM_DATABASE_URL", mode="before")
    @classmethod
    def _asyncpg(cls, v: str | None) -> str | None:
        if not v:
            return v
        return v.replace("postgres://", "postgresql+asyncpg://").replace("postgresql://", "postgresql+asyncpg://")

    @field_validator(
        "S3_BUCKET",
        "S3_REGION",
        "S3_ENDPOINT_URL",
        "AWS_ACCESS_KEY_ID",
        "AWS_SECRET_ACCESS_KEY",
        "SENTRY_DSN",
        "CAPTCHA_SECRET",
        "CAPTCHA_SITE_KEY",
        "CLAMAV_HOST",
        "FRONTEND_URL",
        mode="before",
    )
    @classmethod
    def _blank_to_none(cls, v: str | None) -> str | None:
        return v or None


settings = Settings()
